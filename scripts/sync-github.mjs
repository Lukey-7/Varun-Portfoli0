// Refreshes src/data/github-activity.ts from GitHub through the gh CLI.
// Run with `npm run sync:github`; set GITHUB_LOGIN to read another account.
// The site also refreshes the calendar in the browser, so this snapshot is
// what visitors see when GitHub cannot be reached.
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const login = process.env.GITHUB_LOGIN ?? "Lukey-7";
const query = `query($login: String!) {
  user(login: $login) {
    url
    contributionsCollection {
      contributionCalendar { weeks { contributionDays { date contributionCount } } }
    }
    repositories(first: 100, ownerAffiliations: OWNER, privacy: PUBLIC, isFork: false,
                 orderBy: { field: PUSHED_AT, direction: DESC }) {
      totalCount
      nodes {
        name url pushedAt
        primaryLanguage { name }
        languages(first: 10, orderBy: { field: SIZE, direction: DESC }) { edges { size node { name } } }
      }
    }
  }
}`;

const raw = execFileSync("gh", ["api", "graphql", "-F", `login=${login}`, "-f", `query=${query}`], {
  encoding: "utf8",
  maxBuffer: 1 << 24,
});
const user = JSON.parse(raw).data.user;

const calendar = user.contributionsCollection.contributionCalendar.weeks
  .flatMap((week) => week.contributionDays)
  .map((day) => ({ date: day.date, count: day.contributionCount }));

// Share of code by language across the public repositories.
const bytes = new Map();
for (const repo of user.repositories.nodes)
  for (const edge of repo.languages.edges)
    bytes.set(edge.node.name, (bytes.get(edge.node.name) ?? 0) + edge.size);
const totalBytes = [...bytes.values()].reduce((sum, size) => sum + size, 0) || 1;
const ranked = [...bytes].sort((a, b) => b[1] - a[1]);
const languages = ranked.slice(0, 5).map(([name, size]) => ({
  name,
  share: Math.round((size / totalBytes) * 1000) / 10,
}));
const rest = Math.round((100 - languages.reduce((sum, item) => sum + item.share, 0)) * 10) / 10;
if (rest > 0.5) languages.push({ name: "Other", share: rest });

// Only the repositories this site links to appear in "recently pushed".
const dataDir = join(import.meta.dirname, "..", "src", "data");
const linked = new Set();
for (const file of readdirSync(dataDir).filter((name) => name.endsWith(".ts")))
  for (const match of readFileSync(join(dataDir, file), "utf8").matchAll(
    new RegExp(`github\\.com/${login}/([\\w.-]+)`, "g"),
  ))
    linked.add(match[1].toLowerCase());
linked.add("varun-portfoli0");
const repos = user.repositories.nodes
  .filter((repo) => linked.has(repo.name.toLowerCase()))
  .map((repo) => ({
    name: repo.name,
    url: repo.url,
    language: repo.primaryLanguage?.name ?? null,
    pushedAt: repo.pushedAt,
  }));

const snapshot = {
  login,
  url: user.url,
  fetchedAt: new Date().toISOString(),
  publicRepos: user.repositories.totalCount,
  languages,
  repos,
  calendar,
};

const out = join(dataDir, "github-activity.ts");
writeFileSync(
  out,
  `// Generated by scripts/sync-github.mjs. Run \`npm run sync:github\` to refresh.\n` +
    `import type { GithubActivity } from "@/lib/github-activity";\n\n` +
    `export const githubSnapshot: GithubActivity = ${JSON.stringify(snapshot, null, 2)};\n`,
);
console.log(
  `Wrote ${out}: ${calendar.reduce((sum, day) => sum + day.count, 0)} contributions, ${repos.length} linked repositories.`,
);
